package day1;

public class Java_Varible2 {
	public static void main(String[] args) {
		String name;
		name="홍길동";
		System.out.println(name);
		//변수안에 들어간값 언제든 변경가능
		String hobby=("영화감상");
		System.out.println(hobby);//영화감상이출력됨
		
		hobby="코딩";
		System.out.println(hobby);//코딩이 출력됨
		
		
		//변수선언은 한번만 가능
		int age=31;
		age=15;
		
	}

}
